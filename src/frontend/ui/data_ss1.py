def filter_incidents(search: str = "", status: str = "all") -> List[Dict[str, Any]]:
    results = INCIDENTS
    if status != "all":
        results = [i for i in results if i["status"] == status]
    if search:
        s = search.lower()
        results = [
            i for i in results if s in i["id"].lower() or s in i["sub_text"].lower()
        ]
    return results


def get_incident_detail(incident_id: str) -> Optional[Dict[str, Any]]:
    detail = INCIDENT_DETAILS.get(incident_id)
    if detail is None:
        return None
    # Always recompute progress tabs from live data (covers _DETAIL_25437 too)
    detail = dict(detail)
    detail["progress_tabs"] = compute_progress_tabs(detail)
    vi = detail["vehicle_info"]
    detail["vehicle_info"]["ai_verified"] = all(
        f["ai_status"] == "approved"
        for f in [vi["vin"], vi["license_plate"], vi["odometer"]]
    )
    return detail
