def _tab_status(items: List[Optional[str]]) -> str:
    """Derive approved/flagged/pending from a list of ai_status values."""
    vals = [v for v in items if v]
    if "flagged" in vals:
        return "flagged"
    if vals and all(v == "approved" for v in vals):
        return "approved"
    return "pending"


def compute_progress_tabs(detail: Dict[str, Any]) -> List[Dict[str, str]]:
    """Derive progress-tab statuses from the actual incident data."""
    vi = detail["vehicle_info"]
    bd = detail["breakdown"]

    # Tab 1 — Vehicle ID check: VIN + plate + odometer
    id_status = _tab_status(
        [
            vi["vin"]["ai_status"],
            vi["license_plate"]["ai_status"],
            vi["odometer"]["ai_status"],
        ]
    )

    # Tab 2 — Parts rate & discount: line items that have ai_status
    li_statuses = [
        li.get("ai_status")
        for li in detail["line_items"]
        if li.get("type") == "N" or li.get("price")
    ]
    parts_status = _tab_status(li_statuses)

    # Tab 3 — Labor rate & discount: breakdown.labor items
    labor_status = _tab_status([i["ai_status"] for i in bd["labor"]["items"]])

    # Tab 4 — Materials check: breakdown.materials items
    mat_status = _tab_status([i["ai_status"] for i in bd["materials"]["items"]])

    # Tab 5 — Totals & discount matching: parts + miscellaneous breakdown
    totals_vals = [
        i["ai_status"] for i in bd["parts"]["items"] + bd["miscellaneous"]["items"]
    ]
    totals_status = _tab_status(totals_vals) if any(totals_vals) else "inactive"

    return [
        {"label": "Vehicle ID check", "status": id_status},
        {"label": "Parts rate & discount", "status": parts_status},
        {"label": "Labor rate & discount", "status": labor_status},
        {"label": "Materials check", "status": mat_status},
        {"label": "Totals & discount matching", "status": totals_status},
    ]


